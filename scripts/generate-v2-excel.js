const wb = XLSX.utils.book_new();

function addSheet(wb, name, headers, data) {
  const wsData = [headers, ...data];
  const ws = XLSX.utils.aoa_to_sheet(wsData);

  // Set column widths for readability
  const colWidths = headers.map((h, i) => {
    const headerLen = h.length * 2; // Chinese chars are wider
    const maxDataLen = Math.max(...data.map((row) => String(row[i] || "").length));
    return { wch: Math.max(headerLen, Math.min(maxDataLen * 1.2, 60)) };
  });
  ws["!cols"] = colWidths;

  XLSX.utils.book_append_sheet(wb, ws, name);
}

